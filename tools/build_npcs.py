"""Bake in-game sightings into ComradeCraft/Data/Npcs.lua (npc faction + spot, station spots).

Usage: tools/.venv/Scripts/python -X utf8 tools/build_npcs.py [--out FILE] <ComradeCraft.lua> [more ...]
Inputs are SavedVariables files (WTF/Account/<account>/SavedVariables/ComradeCraft.lua): yours and
the ones friends send. The current Data/Npcs.lua is kept and merged; only our own observations go in.
"""
import argparse
import os
import sys

try:
    from lupa.lua51 import LuaRuntime  # SavedVariables are Lua 5.1
except ImportError:
    from lupa import LuaRuntime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ComradeCraft", "Data", "Npcs.lua")
NEAR = 3  # spots of one station closer than this (map %) are the same one


def lua_tables(lua, t):
    return {k: t[k] for k in t} if t is not None and lua.eval("type")(t) == "table" else {}


# Runs a chunk in an empty environment (no os/io/globals), refusing bytecode; returns that env.
SANDBOX = """
function(src, name, ns)
  if src:byte(1) == 27 then error(name .. ": bytecode refused") end
  local env, fn, err = {}
  if setfenv then
    fn, err = loadstring(src, "=" .. name)
    if fn then setfenv(fn, env) end
  else
    fn, err = load(src, "=" .. name, "t", env)
  end
  if not fn then error(err) end
  fn(nil, ns)
  return env
end
"""


def main(paths, out=OUT):
    lua = LuaRuntime(unpack_returned_tuples=True)
    sandbox = lua.eval(SANDBOX)
    npcs, stations = {}, {}

    def add_npc(npc, fac, m, x, y):
        npc = int(npc)
        cur = npcs.get(npc, [None, None, None, None])
        if fac in ("A", "H", "N"):
            cur[0] = fac
        if m and x is not None and y is not None and int(m) > 0:
            cur[1:] = [int(m), round(float(x), 1), round(float(y), 1)]
        npcs[npc] = cur

    def add_spot(focus, m, x, y):
        if not (m and x is not None and y is not None):
            return
        m, x, y = int(m), round(float(x), 1), round(float(y), 1)
        lst = stations.setdefault(int(focus), [])
        if not any(s[0] == m and abs(s[1] - x) < NEAR and abs(s[2] - y) < NEAR for s in lst):
            lst.append([m, x, y])

    # Current baked data first (kept), then the sightings.
    if os.path.exists(out):
        ns = lua.table()
        with open(out, encoding="utf-8") as f:
            sandbox(f.read(), os.path.basename(out), ns)
        for npc, r in lua_tables(lua, ns.NpcData).items():
            add_npc(npc, r[1], r[2], r[3], r[4])
        for focus, lst in lua_tables(lua, ns.StationData).items():
            for s in lua_tables(lua, lst).values():
                add_spot(focus, s[1], s[2], s[3])

    for path in paths:
        with open(path, encoding="utf-8") as f:
            src = f.read()
        db = sandbox(src, os.path.basename(path), None).ComradeCraftDB
        if db is None:
            print(f"{path}: no ComradeCraftDB, skipped")
            continue
        n0, s0 = len(npcs), sum(map(len, stations.values()))
        spots = lua_tables(lua, db.npcSpots)
        for npc, fac in lua_tables(lua, db.npcFaction).items():
            s = spots.get(npc)
            if s:
                add_npc(npc, fac, s[1], s[2], s[3])
            else:
                add_npc(npc, fac, None, None, None)
        for v in lua_tables(lua, db.foreverVendors).values():
            if v.npc:
                add_npc(v.npc, v.fac, v.map, v.x, v.y)
        for focus, lst in lua_tables(lua, db.stations).items():
            for s in lua_tables(lua, lst).values():
                add_spot(focus, s[1], s[2], s[3])
        for p in lua_tables(lua, db.foreverPeers).values():
            for v in lua_tables(lua, p.vendors).values():
                if v.npc:
                    add_npc(v.npc, v.fac, v.map, v.x, v.y)
            for npc, n in lua_tables(lua, p.npcs).items():
                add_npc(npc, n.fac, n.map, n.x, n.y)
            for focus, lst in lua_tables(lua, p.stations).items():
                for s in lua_tables(lua, lst).values():
                    add_spot(focus, s[1], s[2], s[3])
        print(f"{path}: +{len(npcs) - n0} npcs, +{sum(map(len, stations.values())) - s0} station spots")

    def num(v):
        return "nil" if v is None else (str(int(v)) if float(v).is_integer() else str(v))

    lines = [
        "-- GENERATED by tools/build_npcs.py from in-game sightings (ours and friends'). Do not edit.",
        "local _, ns = ...",
        "-- [npcID] = { faction (\"A\", \"H\", \"N\" or nil), uiMap, x, y }",
        "ns.NpcData = {",
    ]
    for npc in sorted(npcs):
        f, m, x, y = npcs[npc]
        fs = f'"{f}"' if f else "nil"
        lines.append(f"[{npc}]={{{fs},{num(m)},{num(x)},{num(y)}}},")
    lines += ["}", "-- [spellFocusObjectID] = { { uiMap, x, y }, ... }", "ns.StationData = {"]
    for focus in sorted(stations):
        spots = ",".join(f"{{{s[0]},{num(s[1])},{num(s[2])}}}" for s in sorted(stations[focus]))
        lines.append(f"[{focus}]={{{spots}}},")
    lines.append("}")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(npcs)} npcs, {sum(map(len, stations.values()))} station spots -> {out}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    ap = argparse.ArgumentParser(usage=__doc__)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("paths", nargs="+")
    a = ap.parse_args()
    main(a.paths, a.out)
